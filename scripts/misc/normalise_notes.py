"""Normalise transcribed statement heads in references/*/notes.md to one shape.

WHY.  `## references layout` asks for numbered statements transcribed verbatim and, until
today, fixed no shape for them.  Two grew up side by side:

    > **Theorem 1.2.** (1). The only algebraic curvature operator ...     239 of them
    **Theorem A.** *Let $(M,g)$ be a closed Kaehler-Einstein manifold ...*  84 of them

[findings/INDEX-literature.md](../../findings/INDEX-literature.md) is generated by matching
that head, and the screen reads that index FIRST, so a statement in the second shape is
invisible to it.  A cycle keyed on the first shape alone and reported 48 of 86 sources as
never transcribed when they carried their statements in full.

WHAT IT CHANGES, and it is deliberately the smallest thing that removes the ambiguity: a
line beginning `**Kind N.**` gains a `> `.  Nothing else moves, and the statement text is
untouched.

WHAT IT LEAVES ALONE, because these REFER to statements rather than transcribe them:

  * headings that mention a kind, 96 of them
  * table rows citing a statement, 15
  * blockquotes not opening with a bolded kind, 26
  * prose mentions, 197

USE:  python3 scripts/misc/normalise_notes.py --check    reports, changes nothing
      python3 scripts/misc/normalise_notes.py --write    rewrites in place

RUN --check FIRST AND READ IT.  A rewrite across 86 files is the kind of sweep that is
hard to unpick, and a reviewer reading those same files while it runs gets its findings
corrupted, which is worth waiting for rather than racing.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
assert os.path.isdir(os.path.join(ROOT, 'references')), (
    f"ROOT resolved to {ROOT}, which has no references/: this file has moved and the "
    "level count above is stale")

KINDS = "Theorem|Lemma|Proposition|Corollary|Remark|Definition"
# A HEAD, anchored at the line start with no blockquote marker.  Requiring a number or a
# letter after the kind is what separates a transcription from a sentence that happens to
# open with the word: `**Theorem A.**` and `**Lemma 2.5.**` match, `**Theorem, as stated
# by the author, ...**` does not.
BARE_HEAD = re.compile(r'^\*\*(' + KINDS + r')\s+([A-Z0-9][\w.–-]*)\.?\*\*')


def scan():
    """Every line that would gain a marker, as (path, line number, the line)."""
    hits = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'references', '*', 'notes.md'))):
        try:
            lines = open(path, encoding='utf-8').read().split('\n')
        except OSError:
            continue
        for i, line in enumerate(lines, 1):
            if BARE_HEAD.match(line):
                hits.append((path, i, line))
    return hits


def rewrite(hits):
    """Prepend the marker, one file at a time, leaving the statement text untouched."""
    by_file = {}
    for path, i, _ in hits:
        by_file.setdefault(path, []).append(i)
    for path, nums in by_file.items():
        lines = open(path, encoding='utf-8').read().split('\n')
        for i in nums:
            lines[i - 1] = '> ' + lines[i - 1]
        open(path, 'w', encoding='utf-8').write('\n'.join(lines))
    return len(by_file)


if __name__ == '__main__':
    hits = scan()
    if '--write' in sys.argv:
        n = rewrite(hits)
        print(f"rewrote {len(hits)} heads across {n} files")
        print("now rerun scripts/misc/lit_index.py, which reads them")
    else:
        files = {h[0] for h in hits}
        print(f"{len(hits)} bare statement heads across {len(files)} files would gain a marker")
        for path, i, line in hits[:12]:
            print(f"  {os.path.basename(os.path.dirname(path))}:{i}  {line[:86]}")
        if len(hits) > 12:
            print(f"  ... and {len(hits) - 12} more")
        print("\npass --write to rewrite, and not while a reviewer is reading these files")
