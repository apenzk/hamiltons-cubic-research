"""Generate lean/HamiltonsCubic/Results/L50Expand.lean, the Lovelock expansion LL = 16 alpha - 64 gamma.

Enumerates the 720 permutations of the six-index contraction, keeps the 80 with no self-contracted factor, and for
each finds a relabelling of the six summation variables plus one pair symmetry per factor carrying it to +-alpha or
+-gamma. Emits one Lean lemma per survivor, the kernel-decided sorting of survivors, and the assembly. Exact
combinatorics only. Run from the repository root: python3 scripts/misc/gen_L50_expand.py
"""
OUT='lean/HamiltonsCubic/Results/L50Expand.lean'
import itertools
SYMS=[((0,1,2,3),1),((1,0,2,3),-1),((0,1,3,2),-1),((1,0,3,2),1),((2,3,0,1),1),((3,2,0,1),-1),((2,3,1,0),-1),((3,2,1,0),1)]
def sign(p):
    s=1;p=list(p)
    for i in range(len(p)):
        while p[i]!=i:
            j=p[i];p[i],p[j]=p[j],p[i];s=-s
    return s
owner=lambda i:i//2
ALPHA=[(0,1,2,3),(0,1,4,5),(2,3,4,5)]
GAMMA=[(0,1,2,3),(0,4,2,5),(1,5,3,4)]
def match(facs,target):
    for tp in itertools.permutations(range(3)):
        syms=[];tot=1;ok=True
        for f,ti in zip(facs,tp):
            T=target[ti];found=None
            for k,(perm,s) in enumerate(SYMS):
                if tuple(f[j] for j in perm)==T: found=(k,s);break
            if found is None: ok=False;break
            syms.append(found);tot*=found[1]
        if ok: return syms,tot
    return None
surv=[]
for sig in itertools.permutations(range(6)):
    if any(owner(sig[p])==owner(p) for p in range(6)): continue
    facs0=[(2*k,2*k+1,sig[2*k],sig[2*k+1]) for k in range(3)]
    res=None
    for cls,target in (('alpha',ALPHA),('gamma',GAMMA)):
        for pi in itertools.permutations(range(6)):
            facs=[tuple(pi[j] for j in f) for f in facs0]
            m=match(facs,target)
            if m: res=(cls,pi,facs,m);break
        if res: break
    assert res, sig
    surv.append((sig,sign(sig))+res)
from collections import Counter
c=Counter()
for sig,sg,cls,pi,facs,(syms,tot) in surv: c[cls]+=sg*tot
assert len(surv)==80 and c=={'alpha':16,'gamma':-64}, c
surv=[dict(sig=s,sgn=sg,cls=cl,pi=p,facs=f,syms=[k for k,_ in m[0]],tot=m[1]) for s,sg,cl,p,f,m in surv]
SYMNAME={1:'sym1',2:'sym2',3:'sym3',4:'sym4',5:'sym5',6:'sym6',7:'sym7'}
out=[]
out.append('''import HamiltonsCubic.Results.L50Self

set_option linter.style.longLine false
set_option linter.unusedSectionVars false

/-!
# L50, the Lovelock expansion: `LL = 16α − 64γ` on a traceless Weyl tensor

Generated by `scripts/misc/gen_L50_expand.py` from the classification in `scripts/misc/classify_lovelock_terms.py`.
The 640 self-contracted permutations vanish by `selfEdge_zero`. Each of the 80 survivors is `±α` or `±γ` after
relabelling the six summation variables and applying the pair symmetries factor by factor. A kernel `decide`
sorts every survivor into one of the 80 value patterns together with its sign.
-/

namespace HamiltonsCubic.L50Lovelock

open Finset

variable {ι : Type*} [Fintype ι] [DecidableEq ι]

section syms
variable {W : ι → ι → ι → ι → ℝ} (hW : WeylC W)
include hW
theorem sym1 (a b c d : ι) : W a b c d = -W b a c d := hW.anti12 a b c d
theorem sym2 (a b c d : ι) : W a b c d = -W a b d c := hW.anti34 a b c d
theorem sym3 (a b c d : ι) : W a b c d = W b a d c := by rw [hW.anti12, hW.anti34]; ring
theorem sym4 (a b c d : ι) : W a b c d = W c d a b := hW.pair a b c d
theorem sym5 (a b c d : ι) : W a b c d = -W d c a b := by rw [hW.pair, hW.anti12]
theorem sym6 (a b c d : ι) : W a b c d = -W c d b a := by rw [hW.pair, hW.anti34]
theorem sym7 (a b c d : ι) : W a b c d = W d c b a := by rw [hW.pair, hW.anti12, hW.anti34]; ring
end syms
''')
for i,s in enumerate(surv):
    sig,pi,cls,facs,syms,tot=s['sig'],s['pi'],s['cls'],s['facs'],s['syms'],s['tot']
    tgt='alphaC' if cls=='alpha' else 'gammaC'
    hs=' '.join(f'(h{j} : σ {j} = {sig[j]})' for j in range(6))
    coef='' if tot==1 else '-'
    rws=[]
    for f,k in zip(facs,syms):
        if k: rws.append(f'{SYMNAME[k]} hW (y {f[0]}) (y {f[1]}) (y {f[2]}) (y {f[3]})')
    rwline=f'  rw [{", ".join(rws)}]\n' if rws else ''
    out.append(f'''theorem surv_{i} (W : ι → ι → ι → ι → ℝ) (hW : WeylC W) (σ : Equiv.Perm (Fin 6)) {hs} :
    ∑ x, LLterm W σ x = {coef}{tgt} W := by
  rw [sum_relabel (Equiv.ofBijective (![{", ".join(map(str,pi))}] : Fin 6 → Fin 6) (by decide)), {tgt}{", ← Finset.sum_neg_distrib" if tot==-1 else ""}]
  refine Finset.sum_congr rfl fun y _ => ?_
  simp only [LLterm, Function.comp_apply, h0, h1, h2, h3, h4, h5, Equiv.ofBijective_apply]
  simp only [Matrix.cons_val]
{rwline}  try ring
''')
# dispatch and assembly
txt='\n'.join(out)
dis=[]
for s in surv:
    sig=s['sig']
    dis.append('(' + ' ∧ '.join(f'τ {j} = {sig[j]}' for j in range(6)) + f' ∧ Equiv.Perm.sign τ = {"1" if s["sgn"]==1 else "-1"})')
cases=[]
for i,s in enumerate(surv):
    cases.append(f'''  · obtain ⟨h0, h1, h2, h3, h4, h5, hs⟩ := h
    rw [hs, surv_{i} W hW σ h0 h1 h2 h3 h4 h5]
    simp [owner, h0, h1]''')
pat=' | '.join('h' for _ in surv)
txt+=f'''
set_option synthInstance.maxSize 1000000 in
set_option synthInstance.maxHeartbeats 4000000 in
set_option maxRecDepth 100000 in
/-- **The sorting of the survivors**, by kernel evaluation over all 720 permutations: every permutation with no
self-contracted factor has one of 80 value patterns, recorded with its sign. -/
theorem survivor_patterns : ∀ τ : Equiv.Perm (Fin 6), ¬selfEdge τ →
    {(" ∨ " + chr(10) + "    ").join(dis)} := by
  decide

/-- **Each surviving term**: `+α` when the first factor's lower pair lands in one other factor (the cyclic class),
`−γ` otherwise. -/
theorem survivor_term (W : ι → ι → ι → ι → ℝ) (hW : WeylC W) (σ : Equiv.Perm (Fin 6)) (hσ : ¬selfEdge σ) :
    (Equiv.Perm.sign σ : ℝ) * ∑ x, LLterm W σ x = if owner (σ 0) = owner (σ 1) then alphaC W else -gammaC W := by
  rcases survivor_patterns σ hσ with {pat}
{chr(10).join(cases)}

/-- **THE LOVELOCK EXPANSION**: on a Ricci-flat tensor with the Weyl symmetries, `LL = 16α − 64γ`. -/
theorem LL_expand (W : ι → ι → ι → ι → ℝ) (hW : WeylC W) (hRic : ∀ a b, ∑ c, W a c b c = 0) :
    LL W = 16 * alphaC W - 64 * gammaC W := by
  unfold LL
  rw [← Finset.sum_filter_add_sum_filter_not univ selfEdge]
  have h1 : ∑ σ ∈ univ.filter selfEdge, (Equiv.Perm.sign σ : ℝ) * ∑ x, LLterm W σ x = 0 :=
    Finset.sum_eq_zero fun σ hσ => by rw [selfEdge_zero W hW hRic σ (Finset.mem_filter.1 hσ).2, mul_zero]
  rw [h1, zero_add, Finset.sum_congr rfl (fun σ hσ => survivor_term W hW σ (Finset.mem_filter.1 hσ).2),
    Finset.sum_ite]
  simp only [Finset.sum_const, nsmul_eq_mul]
  have c1 : ((univ.filter (fun σ : Equiv.Perm (Fin 6) => ¬selfEdge σ)).filter
      (fun σ => owner (σ 0) = owner (σ 1))).card = 16 := by decide
  have c2 : ((univ.filter (fun σ : Equiv.Perm (Fin 6) => ¬selfEdge σ)).filter
      (fun σ => ¬owner (σ 0) = owner (σ 1))).card = 64 := by decide
  rw [c1, c2]; push_cast; ring

/-- **LINK (b) BELOW DIMENSION SIX**: a Ricci-flat tensor with the Weyl symmetries on at most five index values has
`β = α/2`. -/
theorem collapse {{W : ι → ι → ι → ι → ℝ}} (hW : WeylC W) (hRic : ∀ a b, ∑ c, W a c b c = 0)
    (hcard : Fintype.card ι ≤ 5) : betaC W = alphaC W / 2 :=
  collapse_of_display hW hcard (LL_expand W hW hRic)

end HamiltonsCubic.L50Lovelock
'''
open(OUT,'w').write(txt)
