_ROOT = _os.path.abspath(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '..', '..', '..'))
import sys, time
sys.path.insert(0, _os.path.join(_ROOT, 'scripts'))
import numpy as np
from fractions import Fraction
from itertools import combinations
from review_r38_core import rref, nullspace, pair_data, signed
LOG = _os.path.join(_ROOT, 'agent_logs/review_r38_exact.log')
def log(m):
    open(LOG, 'a').write(time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()) + ' ' + m + '\n')
    print(m, flush=True)

def so_basis(m):
    out = []
    for i in range(m):
        for j in range(i + 1, m):
            X = np.zeros((m, m), dtype=np.int64); X[i, j] = 1; X[j, i] = -1
            out.append(X)
    return out

def refl(m):
    r = np.eye(m, dtype=np.int64); r[0, 0] = -1
    return r

# ---- ambient spaces, each with: dim, dLie(X) matrix, refl matrix -------------
def sp_vector(m):
    d = m
    return d, (lambda X: X.copy()), refl(m)

def sp_lambda2(m):
    pairs, idx = pair_data(m); d = len(pairs)
    def dL(X):
        M = np.zeros((d, d), dtype=np.int64)
        for b, (k, l) in enumerate(pairs):
            for r in range(m):
                if X[r, k]:
                    s = signed(idx, r, l)
                    if s: M[s[0], b] += X[r, k] * s[1]
                if X[r, l]:
                    s = signed(idx, k, r)
                    if s: M[s[0], b] += X[r, l] * s[1]
        return M
    R = np.zeros((d, d), dtype=np.int64)
    r = refl(m)
    for b, (k, l) in enumerate(pairs):
        R[idx[(k, l)], b] = r[k, k] * r[l, l]
    return d, dL, R

def sp_sym2(m):
    keys = [(i, j) for i in range(m) for j in range(i, m)]
    idx = {k: a for a, k in enumerate(keys)}; d = len(keys)
    def pos(i, j): return idx[(i, j)] if i <= j else idx[(j, i)]
    def dL(X):
        M = np.zeros((d, d), dtype=np.int64)
        for b, (i, j) in enumerate(keys):
            for r in range(m):
                if X[r, i]: M[pos(r, j), b] += X[r, i]
                if X[r, j]: M[pos(i, r), b] += X[r, j]
        return M
    R = np.zeros((d, d), dtype=np.int64)
    r = refl(m)
    for b, (i, j) in enumerate(keys):
        R[b, b] = r[i, i] * r[j, j]
    return d, dL, R

def sp_l2_r(m):
    """Lambda^2 (x) R^m, coords (a,c) with a a 2-plane index."""
    pairs, idx = pair_data(m); n2 = len(pairs); d = n2 * m
    d2, dL2, R2 = sp_lambda2(m)
    def dL(X):
        M = np.zeros((d, d), dtype=np.int64)
        L = dL2(X)
        for a in range(n2):
            for c in range(m):
                col = a * m + c
                for a2 in range(n2):
                    if L[a2, a]: M[a2 * m + c, col] += L[a2, a]
                for c2 in range(m):
                    if X[c2, c]: M[a * m + c2, col] += X[c2, c]
        return M
    R = np.zeros((d, d), dtype=np.int64)
    r = refl(m)
    for a in range(n2):
        for c in range(m):
            R[a * m + c, a * m + c] = 0
    for a in range(n2):
        for c in range(m):
            R[a * m + c, a * m + c] = R2[a, a] * r[c, c]
    return d, dL, R

def sp_symlambda2(m):
    """Sym^2(Lambda^2), coords (a<=b)."""
    n2 = len(pair_data(m)[0])
    keys = [(a, b) for a in range(n2) for b in range(a, n2)]
    idx = {k: i for i, k in enumerate(keys)}; d = len(keys)
    d2, dL2, R2 = sp_lambda2(m)
    def pos(a, b): return idx[(a, b)] if a <= b else idx[(b, a)]
    def dL(X):
        L = dL2(X)
        M = np.zeros((d, d), dtype=np.int64)
        for col, (a, b) in enumerate(keys):
            for a2 in range(n2):
                if L[a2, a]: M[pos(a2, b), col] += L[a2, a]
            for b2 in range(n2):
                if L[b2, b]: M[pos(a, b2), col] += L[b2, b]
        return M
    R = np.zeros((d, d), dtype=np.int64)
    for col, (a, b) in enumerate(keys):
        R[col, col] = R2[a, a] * R2[b, b]
    return d, dL, R

# ---- submodules ---------------------------------------------------------------
def sub_basis(rows, d):
    return nullspace(rows, d)

def mod_trivial(m):
    return 1, [np.zeros((1, 1), dtype=object)] , np.eye(1, dtype=object), 'trivial'

def restrict(d, dL, R, basis):
    """basis: list of Fraction vectors spanning an invariant subspace; return
    (dim, [dLie matrices in that basis], refl matrix in that basis)."""
    k = len(basis)
    B = [[Fraction(x) for x in v] for v in basis]
    # coordinates: solve B^T c = w
    def coords(w):
        rows = [[B[j][i] for j in range(k)] + [Fraction(w[i])] for i in range(d)]
        R2, piv = rref(rows, k + 1)
        assert k not in piv, 'vector not in span'
        c = [Fraction(0)] * k
        for ri, pc in enumerate(piv):
            c[pc] = R2[ri][k]
        return c
    return coords

def module_matrices(d, dL, Rm, basis, gens):
    k = len(basis)
    coords = restrict(d, dL, Rm, basis)
    mats = []
    for X in gens + ['refl']:
        A = np.zeros((k, k), dtype=object)
        M = Rm if X is 'refl' else dL(X)
        for j in range(k):
            w = [sum(Fraction(int(M[i][t])) * Fraction(basis[j][t]) for t in range(d)) for i in range(d)]
            c = coords(w)
            for i in range(k):
                A[i, j] = c[i]
        mats.append(A)
    return mats

def hom_dim(matsA, matsB):
    """dim { M : M A_k = B_k M } with M of shape (dimB, dimA)."""
    dA = matsA[0].shape[0]; dB = matsB[0].shape[0]
    nv = dA * dB
    rows = []
    for A, Bm in zip(matsA, matsB):
        for i in range(dB):
            for j in range(dA):
                r = [Fraction(0)] * nv
                for t in range(dA):
                    if A[t, j] != 0: r[i * dA + t] += Fraction(A[t, j])
                for t in range(dB):
                    if Bm[i, t] != 0: r[t * dA + j] -= Fraction(Bm[i, t])
                if any(r): rows.append(r)
    _, piv = rref(rows, nv)
    return nv - len(piv)

log('P5: O(m)-commutant / Hom dimensions for the constituents of the ten-summand list')
for m in [3, 4]:
    gens = so_basis(m)
    mods = {}
    # R^m
    d, dL, Rm = sp_vector(m)
    mods['R^m'] = module_matrices(d, dL, Rm, [[Fraction(1 if i == j else 0) for i in range(d)] for j in range(d)], gens)
    # Lambda^2
    d, dL, Rm = sp_lambda2(m)
    mods['Lambda^2'] = module_matrices(d, dL, Rm, [[Fraction(1 if i == j else 0) for i in range(d)] for j in range(d)], gens)
    # S^2_0
    d, dL, Rm = sp_sym2(m)
    keys = [(i, j) for i in range(m) for j in range(i, m)]
    trace_row = [Fraction(1) if i == j else Fraction(0) for (i, j) in keys]
    b = nullspace([trace_row], d)
    mods['S^2_0'] = module_matrices(d, dL, Rm, b, gens)
    # X_m inside Lambda^2 (x) R^m
    d, dL, Rm = sp_l2_r(m)
    pairs, idx = pair_data(m); n2 = len(pairs)
    rows = []
    for a, b3, c in combinations(range(m), 3):
        r = [Fraction(0)] * d
        r[idx[(a, b3)] * m + c] += 1
        r[idx[(a, c)] * m + b3] -= 1
        r[idx[(b3, c)] * m + a] += 1
        rows.append(r)
    for a in range(m):
        r = [Fraction(0)] * d
        for c in range(m):
            s = signed(idx, a, c)
            if s: r[s[0] * m + c] += s[1]
        if any(r): rows.append(r)
    bX = nullspace(rows, d)
    mods['X_m'] = module_matrices(d, dL, Rm, bX, gens)
    # Weyl_m inside Sym^2(Lambda^2)
    d, dL, Rm = sp_symlambda2(m)
    from review_r38_core import sym_vars, bianchi_rows, ricci_rows
    N = n2
    cols, ncols = sym_vars(N)
    assert ncols == d
    wrows = bianchi_rows(m, cols, ncols) + ricci_rows(m, cols, ncols)
    bW = nullspace(wrows, d) if wrows else []
    if bW:
        mods['Weyl_m'] = module_matrices(d, dL, Rm, bW, gens)
    names = list(mods)
    log(f'  m={m}: dims ' + ', '.join(f'{k}={mods[k][0].shape[0]}' for k in names))
    for k in names:
        log(f'    End_O({m})({k}) = {hom_dim(mods[k], mods[k])}   (1 => absolutely irreducible, real type)')
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            h = hom_dim(mods[names[i]], mods[names[j]])
            if h != 0:
                log(f'    !! Hom_O({m})({names[i]},{names[j]}) = {h}  (isomorphic constituents)')
    log(f'    all cross-Homs zero: '
        f'{all(hom_dim(mods[names[i]], mods[names[j]]) == 0 for i in range(len(names)) for j in range(i+1, len(names)))}')
