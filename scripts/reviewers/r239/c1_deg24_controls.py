"""r239, claim 1 -- controls at weighted degree EXACTLY 24, the degree at which 89 lives.

The three control reps have invariant rings that are known free polynomial algebras
in the stable range, so the degree-24 coefficient of their Molien series is known
combinatorially:
  V         invariants generated by |x|^2               -> 1 if k even else 0
  S^2_0 V   invariants tr(A^2),tr(A^3),...  free        -> partitions of k, parts >= 2
  Lambda^2  invariants tr(A^2),tr(A^4),...  free        -> partitions of k, even parts
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from c1_haar_moments import (CHI_V, CHI_S20, CHI_LAM2, CHI_W,
                             sym_power_char, haar_O, weighted_degree)

def npart(k, minpart=1, step=1):
    memo = {}
    def go(k, m):
        if k == 0:
            return 1
        if (k, m) in memo:
            return memo[(k, m)]
        t = 0
        p = m
        while p <= k:
            t += go(k - p, p)
            p += step
        memo[(k, m)] = t
        return t
    return go(k, minpart)

cases = [("V, k=24", CHI_V, 24, 1),
         ("S^2_0, k=12", CHI_S20, 12, npart(12, 2, 1)),
         ("Lambda^2, k=12", CHI_LAM2, 12, npart(12, 2, 2))]
for name, chi, k, want in cases:
    ch = sym_power_char(chi, k)
    val = haar_O(ch)
    assert val.denominator == 1
    print(f"  {name}: weighted degree {weighted_degree(ch)}, dim = {int(val)}, expected {int(want)}  "
          f"{'MATCH' if int(val) == int(want) else '*** MISMATCH ***'}")

ch = sym_power_char(CHI_W, 6)
print(f"  Weyl, k=6: weighted degree {weighted_degree(ch)}, dim = {int(haar_O(ch))}")
