"""r203: the block bookkeeping behind claims 2 and 6, from the weights alone.

Inputs: the 24 highest weights and their multiplicities in Sym^3(Weyl_5).
Everything else -- dimensions, the 7770, the 65/24/89, the 3570, the 16 even
blocks, the 25/36 post-orbit counts and the two-3x3/five-2x2/nine-scalar shape
-- is recomputed here from the Weyl dimension formula for B_2.

Then the piece the record does NOT state: the multiplicity-space description of
  rank of the certificate map = dim (K.K)^{O(5)},  K = cubics vanishing on the
orbit, and the identity 36 + 29 = 65 that ties claim 6 to claim 3.
"""
from fractions import Fraction as F

MULT = {(4,2):4, (2,2):4, (3,2):3,
        (5,2):2, (4,3):2, (4,4):2, (4,1):2, (3,1):2, (4,0):2, (2,1):2, (3,0):2, (2,0):2,
        (6,6):1, (6,4):1, (6,3):1, (6,2):1, (6,0):1, (5,4):1, (5,3):1, (5,1):1,
        (5,0):1, (3,3):1, (1,0):1, (0,0):1}
REC_DIM = {(4,2):220,(2,2):35,(3,2):105,(5,2):390,(4,3):231,(4,4):165,(4,1):154,
           (3,1):81,(4,0):55,(2,1):35,(3,0):30,(2,0):14,(6,6):455,(6,4):810,
           (6,3):770,(6,2):625,(6,0):140,(5,4):429,(5,3):455,(5,1):260,(5,0):91,
           (3,3):84,(1,0):5,(0,0):1}

def dim_B2(l1, l2):
    """Weyl dimension formula, positive roots e1-e2, e1+e2, e1, e2, rho=(3/2,1/2)."""
    a, b = F(2*l1+3, 2), F(2*l2+1, 2)
    num = (a-b)*(a+b)*a*b
    den = F(1)*F(2)*F(3,2)*F(1,2)
    return num/den
def casimir(l1, l2): return l1*(l1+3) + l2*(l2+1)

print("=== the 24 blocks, dimensions recomputed from the weights ===")
bad = [lam for lam in MULT if dim_B2(*lam) != REC_DIM[lam]]
print(f"  Weyl dimension formula reproduces all 24 recorded dimensions: {not bad}")
tot = sum(MULT[l]*int(dim_B2(*l)) for l in MULT)
print(f"  sum m_lam d_lam = {tot}   (dim Sym^3(35) = {35*36*37//6}: {tot == 35*36*37//6})")
m = list(MULT.values())
print(f"  blocks {len(MULT)}, sum m = {sum(m)}, sum m(m+1)/2 = {sum(x*(x+1)//2 for x in m)},"
      f" sum m(m-1)/2 = {sum(x*(x-1)//2 for x in m)}, sum m^2 = {sum(x*x for x in m)}")
cas = {}
for l in MULT: cas.setdefault(casimir(*l), []).append(l)
print(f"  distinct degree-2 Casimir values: {len(cas)}; collisions:"
      f" {[v for v in cas.values() if len(v) > 1]}")

print("\n=== the orbit constraint: lambda_2 even ===")
even = [l for l in MULT if l[1] % 2 == 0]
odd  = [l for l in MULT if l[1] % 2 == 1]
print(f"  even blocks: {len(even)}, sum of dims = {sum(int(dim_B2(*l)) for l in even)}")
print(f"  sum of multiplicities over even blocks = {sum(MULT[l] for l in even)}   <- call it E")
mK = {l: MULT[l] - (1 if l[1] % 2 == 0 else 0) for l in MULT}
print(f"  post-orbit multiplicities sum = {sum(mK.values())}")
print(f"  post-orbit unknowns = sum m^K(m^K+1)/2 = {sum(v*(v+1)//2 for v in mK.values())}")
shape = {}
for v in mK.values():
    if v: shape[v] = shape.get(v, 0) + 1
print(f"  shape: {dict(sorted(shape.items(), reverse=True))}  (size -> how many blocks)")
print(f"  blocks that die outright: {sorted(l for l in mK if mK[l] == 0)}")
print(f"  surviving Casimir collisions:"
      f" {[v for v in cas.values() if len(v) > 1 and all(mK[l] for l in v)]}")

print("\n=== the identity that ties claim 6 to claim 3 ===")
n65 = sum(x*(x+1)//2 for x in m)
n36 = sum(v*(v+1)//2 for v in mK.values())
E = sum(MULT[l] for l in even)
print(f"  dim Sym^2(Sym^3)^O(5)          = {n65}")
print(f"  dim Sym^2(K)^O(5)              = {n36}")
print(f"  dim of the annihilator of K.K  = {E}   (sum of m over even blocks)")
print(f"  {n36} + {E} = {n36+E}: {n36+E == n65}")
print("""
  WHY.  Write Sym^3 = K + C with C the copy generated by W_0^3, one line
  u_lam in each even block's multiplicity space C^{m_lam} and none in an odd
  block.  An invariant F in Sym^6 has an equivariant middle catalecticant
  Cat_F, block-diagonal with a symmetric m_lam x m_lam matrix M_lam.  F kills
  K.K iff P_{u^perp} M_lam P_{u^perp} = 0 for every block, i.e. M_lam = 0 on an
  odd block and M_lam = alpha u u^T + u c^T + c u^T (dimension m_lam) on an
  even one.  So the annihilator of K.K inside the 65 has dimension E = %d, and
  the complement is exactly the %d unknowns.  The 36 of claim 6 and the 65 of
  claim 3 are the same computation read two ways.""" % (E, n36))

print("""
=== what the rank actually is ===
  rank = dim (K.K)^{O(5)} = 14 - dim {F in (Sym^6)^inv : Cat_F(K,K) = 0}.
  The 14-dimensional image of Cat sits inside the 65; the annihilator of K.K
  is a %d-dimensional subspace of the 65.  Two subspaces of dimensions 14 and
  %d in a 65-dimensional space meet in 14 + %d - 65 = %d dimensions when they
  are in general position, so the intersection would be ZERO -- but it is not,
  because A(W_0^6) lies in it.  rank <= 13 is exactly that one forced drop.
  rank = 13 iff no SECOND coincidence occurs.""" % (E, E, E, 14 + E - 65))
