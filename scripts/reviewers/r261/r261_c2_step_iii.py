import numpy as np

N = 3                                    # dim V
rng = np.random.default_rng(3)

def matchings(pts):
    if not pts:
        yield ()
        return
    a, rest = pts[0], pts[1:]
    for i, b in enumerate(rest):
        for m in matchings(rest[:i] + rest[i+1:]):
            yield ((a, b),) + m

def matching_vector(D, m):
    """the invariant tensor prod delta over the pairs of D, as a flat vector."""
    v = np.zeros((N,) * m)
    it = np.nditer(np.zeros((N,) * m), flags=['multi_index'])
    for _ in it:
        t = it.multi_index
        if all(t[a] == t[b] for a, b in D):
            v[t] = 1.0
    return v.reshape(-1)

def swap(v, m, i, j):
    a = v.reshape((N,) * m)
    return np.swapaxes(a, i, j).reshape(-1)

def contract(v, m, i, j):
    """the cup-cap e_{ij}: sum_b v[.. b .. b ..] placed at equal indices i,j."""
    a = v.reshape((N,) * m)
    tr = np.trace(a, axis1=i, axis2=j)                       # legs i,j removed
    out = np.zeros((N,) * m)
    idx = [slice(None)] * m
    for b in range(N):
        idx[i], idx[j] = b, b
        out[tuple(idx)] = tr
        idx[i], idx[j] = slice(None), slice(None)
    return out.reshape(-1)

def block_perm(v, m, legs, perm):
    """permute three 2-leg blocks of `legs` by `perm`."""
    a = v.reshape((N,) * m)
    order = list(range(m))
    blocks = [legs[0:2], legs[2:4], legs[4:6]]
    newblocks = [blocks[perm[k]] for k in range(3)]
    flat_src = [x for blk in newblocks for x in blk]
    for pos, src in zip(legs, flat_src):
        order[pos] = src
    return np.transpose(a, order).reshape(-1)

def projector_e(V, m, legs):
    """apply e = Sym_3 . (A tensor A tensor A) to every column of V."""
    out = np.zeros_like(V)
    for k in range(V.shape[1]):
        v = V[:, k]
        for (i, j) in (legs[0:2], legs[2:4], legs[4:6]):
            v = 0.5 * (v - swap(v, m, i, j))
        s = np.zeros_like(v)
        from itertools import permutations
        for p in permutations(range(3)):
            s = s + block_perm(v, m, legs, p)
        out[:, k] = s / 6.0
    return out

def rank(M, tol=1e-9):
    return 0 if M.size == 0 else np.linalg.matrix_rank(M, tol=tol)

def closure(seed, m, legs):
    """span{ nu(D) c_0 : D in B_f(n) }, built from the algebra's GENERATORS.

    B_f(n) is generated by the adjacent transpositions and one contraction, so
    the module generated by c_0 is the closure of {c_0} under those maps.
    """
    basis = seed.reshape(-1, 1) / np.linalg.norm(seed)
    frontier = [seed]
    while frontier:
        nxt = []
        for v in frontier:
            for k in range(len(legs) - 1):
                i, j = legs[k], legs[k+1]
                for w in (swap(v, m, i, j), contract(v, m, i, j)):
                    nw = np.linalg.norm(w)
                    if nw < 1e-12:
                        continue
                    w = w / nw
                    resid = w - basis @ (basis.T @ w)
                    if np.linalg.norm(resid) > 1e-8:
                        basis = np.column_stack([basis, resid / np.linalg.norm(resid)])
                        nxt.append(w)
        frontier = nxt
    return basis

