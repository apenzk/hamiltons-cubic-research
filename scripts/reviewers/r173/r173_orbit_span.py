import numpy as np
rng = np.random.default_rng(173)

def weyl_project(R, n):
    Ric = np.einsum('abad->bd', R); Sc = np.trace(Ric); g = np.eye(n)
    KN = (np.einsum('ac,bd->abcd', g, Ric) - np.einsum('ad,bc->abcd', g, Ric)
        - np.einsum('bc,ad->abcd', g, Ric) + np.einsum('bd,ac->abcd', g, Ric))
    G  = np.einsum('ac,bd->abcd', g, g) - np.einsum('ad,bc->abcd', g, g)
    return R - KN/(n-2) + Sc*G/((n-1)*(n-2))

J = np.zeros((4,4)); J[0,1]=-1; J[1,0]=1; J[2,3]=-1; J[3,2]=1
g4 = np.eye(4)
Rcp = (np.einsum('ac,bd->abcd', g4,g4) - np.einsum('ad,bc->abcd', g4,g4)
     + np.einsum('ac,bd->abcd', J,J)   - np.einsum('ad,bc->abcd', J,J)
     + 2*np.einsum('ab,cd->abcd', J,J))
W0 = np.zeros((5,)*4); W0[:4,:4,:4,:4] = weyl_project(Rcp, 4)
W0 /= np.sqrt(np.einsum('abcd,abcd->', W0, W0))

def rand_so5():
    A = rng.standard_normal((5,5))
    Qm, Rm = np.linalg.qr(A)
    Qm = Qm * np.sign(np.diag(Rm))
    if np.linalg.det(Qm) < 0: Qm[:, 0] = -Qm[:, 0]
    return Qm

N = 4800
X = np.empty((N, 625))
for i in range(N):
    g = rand_so5()
    X[i] = np.einsum('ap,bq,cr,ds,pqrs->abcd', g,g,g,g, W0, optimize=True).ravel()
print("sample built:", X.shape)

Gm = X @ X.T
K  = Gm**3
ev = np.linalg.eigvalsh(K)[::-1]
print("kernel eigenvalues: max %.6g  min %.3g" % (ev[0], ev[-1]))
for tol in (1e-6, 1e-8, 1e-10, 1e-12):
    print("  rank at rel-tol %-6g : %d" % (tol, int((ev > tol*ev[0]).sum())))

r = int((ev > 1e-9*ev[0]).sum())
print("\nRANK =", r, " (record asserts 3570);  dim Sym^3 = 7770, so ker G >=", r,
      "and rank G <=", 7770 - r, " -> %.3f%%" % (100.0*r/7770))

