"""Reviewer 173 -- how much smaller than 65 the orbit constraint makes item 3c's SDP.

RUN:  python3 scripts/reviewers/r173/r173_surviving_params.py   (instant)

Structure.  G = (+)_lambda G_lambda (x) I_{d_lambda} with G_lambda of size m_lambda.
The span of {v(gW_0)} is the cyclic module generated by v(W_0); by Burnside its
lambda-part is U_lambda (x) V_lambda with U_lambda the column space of the isotypic
component of v(W_0), so dim span = sum_lambda u_lambda d_lambda with u_lambda <= m_lambda.
G kills that span, so G_lambda is supported on U_lambda^perp and carries
(m_lambda - u_lambda)(m_lambda - u_lambda + 1)/2 unknowns.

Measured: dim span = 3570 (r173_orbit_span.py, rebuilt from the Veronese kernel).
Exact integer programme over that one equation gives the bracket.
"""
BLOCKS = [(810,1),(770,1),(625,1),(455,1),(455,1),(429,1),(390,2),(260,1),(231,2),
          (220,4),(165,2),(154,2),(140,1),(105,3),(91,1),(84,1),(81,2),(55,2),
          (35,2),(35,4),(30,2),(14,2),(5,1),(1,1)]
TARGET = 3570
print("blocks", len(BLOCKS), " dim check", sum(d*m for d,m in BLOCKS),
      " unknowns", sum(m*(m+1)//2 for d,m in BLOCKS))

def solve(blocks, target, forced):
    NEG = None
    lo = {0: 0}; hi = {0: 0}
    for k,(d,m) in enumerate(blocks):
        nlo, nhi = {}, {}
        rng = range(m+1) if k not in forced else [forced[k]]
        for s in lo:
            for u in rng:
                t = s + u*d
                if t > target: continue
                c = (m-u)*(m-u+1)//2
                if t not in nlo or lo[s]+c < nlo[t]: nlo[t] = lo[s]+c
                if t not in nhi or hi[s]+c > nhi[t]: nhi[t] = hi[s]+c
        lo, hi = nlo, nhi
    return lo.get(target), hi.get(target)

a,b = solve(BLOCKS, TARGET, {})
print("\nunconstrained bracket           : min %s, max %s surviving parameters" % (a,b))
# the two blocks r173 proves occupied: trivial (tr W_0^3 = 1/sqrt6) and vector (T(W_0) != 0)
forced = {23: 1, 22: 1}
a2,b2 = solve(BLOCKS, TARGET, forced)
print("with ()_1 and (1)_5 forced u = 1 : min %s, max %s" % (a2,b2))
print("\nSo the two blocks plan.md names as 'already determined' are exactly 2 of the 65;")
print("the orbit constraint as a whole removes far more, but which is not pinned by")
print("the span dimension alone.")
