"""r207: the two Casimir values that do NOT determine their block, settled.

c = 40 carries both (5,0) [dim 91] and (4,3) [dim 231]; c = 60 carries both
(5,4) [429] and (6,2) [625].  For each, project u = W_0^3 onto that Casimir
eigenvalue and measure the dimension of the so(5)-module the projection
generates -- exactly, mod p, using SO(5,F_p) elements from the Cayley transform.
The three possible answers (d1, d2, d1+d2) are far apart, so the measurement
names the blocks.
"""
import numpy as np, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common207 import P, GENS, SHAT, build, lam2_grp, make_casimir

rows, piv, coords, R = build()
cas3 = make_casimir(R, rows)
u0 = coords(SHAT.ravel() % P)
T = np.einsum('i,j,k->ijk', u0, u0, u0) % P

PRESENT = [0,4,10,16,18,24,28,34,40,46,48,54,60,74,96]      # roots of the minpoly

def project(T, target):
    out = T.copy()
    for c in PRESENT:
        if c == target: continue
        out = (cas3(out) - c*out) % P
        out = out * pow((target - c) % P, P-2, P) % P
    chk = (cas3(out) - target*out) % P
    assert not chk.any(), "projection is not a Casimir eigenvector"
    assert out.any(), f"the c = {target} component of u is ZERO"
    return out

rng = np.random.default_rng(7207)
def rand_so5_modp():
    while True:
        A = rng.integers(0, P, (5,5)); A = (A - A.T) % P
        M = (np.eye(5, dtype=np.int64) + A) % P
        Minv = inv_modp(M)
        if Minv is not None:
            g = ((np.eye(5, dtype=np.int64) - A) % P) @ Minv % P
            return g

def inv_modp(M):
    n = len(M); A = np.concatenate([M % P, np.eye(n, dtype=np.int64)], 1)
    r = 0
    for c in range(n):
        p_ = next((k for k in range(r, n) if A[k, c] % P), None)
        if p_ is None: return None
        A[[r, p_]] = A[[p_, r]]
        A[r] = A[r] * pow(int(A[r, c]), P-2, P) % P
        for k in range(n):
            if k != r and A[k, c]: A[k] = (A[k] - A[k, c]*A[r]) % P
        r += 1
    return A[:, n:]

def rep(g):
    """g acting on Weyl_5 in the basis `rows`: 35x35 mod P."""
    L = lam2_grp(g); Lt = L.T % P
    M = np.zeros((35,35), dtype=np.int64)
    for k in range(35):
        A = rows[k].reshape(10,10)
        M[:, k] = coords((L @ A % P @ Lt % P).ravel())
    return M % P

def module_dim(v, cap):
    pivots, pcols = [], []
    def add(x):
        x = x.copy() % P
        for r, c in zip(pivots, pcols):
            if x[c]: x = (x - x[c]*r) % P
        nz = np.nonzero(x)[0]
        if not len(nz): return False
        c = int(nz[0]); pivots.append(x * pow(int(x[c]), P-2, P) % P); pcols.append(c)
        return True
    add(v.ravel())
    miss = 0
    while len(pivots) < cap and miss < 40:
        M = rep(rand_so5_modp())
        w = (np.einsum('ip,pjk->ijk', M, v) % P)
        w = (np.einsum('jp,ipk->ijk', M, w) % P)
        w = (np.einsum('kp,ijp->ijk', M, w) % P)
        miss = 0 if add(w.ravel()) else miss + 1
    return len(pivots)

for target, cands in ((40, "(5,0)=91 / (4,3)=231 / both=322"),
                      (60, "(5,4)=429 / (6,2)=625 / both=1054")):
    v = project(T, target)
    cap = 400 if target == 40 else 1150
    d = module_dim(v, cap)
    print(f"c = {target}: module generated by the projection has dim {d}    [{cands}]")
    sys.stdout.flush()
