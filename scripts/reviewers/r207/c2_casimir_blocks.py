"""r207, claim 2 (premise), EXACT: which so(5) blocks occur in C = span{g.W_0^3}.

C is the module generated by u = W_0^3 in Sym^3(Weyl_5).  A block lambda meets C
exactly when the isotypic projection of u is nonzero, and the Casimir acts on
that block by c(lambda) = l1^2 + l2^2 + 3 l1 + l2.  So the set of blocks meeting
C is read off the MINIMAL POLYNOMIAL of the Casimir on the Krylov space of u --
computed here mod p, in exact arithmetic, with nothing imported from the repo.

Everything is built from the CP^2 description of W_0.  Weyl_5 itself is obtained
as the so(5)-module generated by W_0 (it comes out 35-dimensional, which is
already a check that W_0 sits in an irreducible copy of V_(2,2)).
"""
import numpy as np, itertools, sys

P = 46337
PAIRS = list(itertools.combinations(range(5), 2))
PIDX = {p: k for k, p in enumerate(PAIRS)}

def wedge(i, j):
    v = np.zeros(10, dtype=np.int64)
    if i == j: return v
    s = 1
    if i > j: i, j, s = j, i, -1
    v[PIDX[(i, j)]] = s
    return v

w1 = wedge(0,1) + wedge(2,3); w2 = wedge(0,2) - wedge(1,3); w3 = wedge(0,3) + wedge(1,2)
Shat = 2*np.outer(w1,w1) - np.outer(w2,w2) - np.outer(w3,w3)     # 6*W_0*sqrt(6)/... , integer

# so(5) basis and its action on Lambda^2 R^5
def lam2_alg(a, b):
    """d/dt Lambda^2(exp(t M_ab)) as a 10x10 integer matrix."""
    X = np.zeros((5,5), dtype=np.int64); X[a,b] = 1; X[b,a] = -1
    L = np.zeros((10,10), dtype=np.int64)
    for c,(i,j) in enumerate(PAIRS):
        v = np.zeros(10, dtype=np.int64)
        for k in range(5):
            if X[k,i]: v += X[k,i]*wedge(k, j)
            if X[k,j]: v += X[k,j]*wedge(i, k)
        L[:, c] = v
    return L
GENS = [lam2_alg(a,b) for a,b in PAIRS]
for L in GENS: assert np.array_equal(L, -L.T), "lambda^2(X) must be antisymmetric"

def act(L, A):  return (L @ A - A @ L) % P

# --- Weyl_5 as the module generated by W_0 --------------------------------
rows, piv = [], []                     # reduced rows, pivot columns
raw = []                               # the unreduced generators, in order
def reduce_add(v):
    v = v.copy() % P
    for r, c in zip(rows, piv):
        if v[c]: v = (v - v[c]*r) % P
    nz = np.nonzero(v)[0]
    if not len(nz): return False
    c = int(nz[0]); v = (v * pow(int(v[c]), P-2, P)) % P
    for k in range(len(rows)):
        if rows[k][c]: rows[k] = (rows[k] - rows[k][c]*v) % P
    rows.append(v); piv.append(c)
    return True

def coords(v):
    """coordinates of v in the basis `raw` (which spans the same space)."""
    v = v.copy() % P; out = np.zeros(len(rows), dtype=np.int64)
    for k, (r, c) in enumerate(zip(rows, piv)):
        if v[c]: out[k] = v[c]; v = (v - v[c]*r) % P
    assert not v.any(), "vector left the module"
    return out
# NB: `rows` is the RREF basis; coordinates above are w.r.t. `rows`.

frontier = [Shat.ravel() % P]
reduce_add(frontier[0])
while frontier:
    nxt = []
    for v in frontier:
        A = v.reshape(10,10)
        for L in GENS:
            w = act(L, A).ravel()
            if reduce_add(w): nxt.append(w)
    frontier = nxt
D = len(rows)
print(f"dim of the so(5)-module generated by W_0 : {D}   (expect 35)")
assert D == 35

# --- so(5) action in that basis -------------------------------------------
R = []
for L in GENS:
    Rm = np.zeros((D, D), dtype=np.int64)
    for k in range(D):
        Rm[:, k] = coords(act(L, rows[k].reshape(10,10)).ravel())
    R.append(Rm % P)

# --- Casimir on Weyl_5: calibrate the scale -------------------------------
Om = np.zeros((D,D), dtype=np.int64)
for Rm in R: Om = (Om + Rm @ Rm % P) % P
kap = int(Om[0,0])
assert np.array_equal(Om, (kap*np.eye(D, dtype=np.int64)) % P), "Casimir not scalar on Weyl_5"
# c(2,2) = 16, so raw eigenvalue = kap/16 * c(lambda)
scale = kap * pow(16, P-2, P) % P
print(f"raw Casimir on Weyl_5 = {kap} (mod {P}); scale = raw/c, c(2,2)=16")

def cval(l1, l2): return l1*l1 + l2*l2 + 3*l1 + l2
MULT = {(0,0):1,(1,0):1,(2,0):2,(3,0):2,(2,1):2,(2,2):4,(4,0):2,(3,1):2,
        (3,3):1,(5,0):1,(3,2):3,(6,0):1,(4,1):2,(4,4):2,(4,2):4,(4,3):2,
        (5,1):1,(5,2):2,(5,4):1,(5,3):1,(6,6):1,(6,2):1,(6,3):1,(6,4):1}

# --- u = W_0^3 in Sym^3, and the Krylov space of the Casimir --------------
u0 = coords(Shat.ravel() % P)
T = np.einsum('i,j,k->ijk', u0, u0, u0) % P
def deriv(Rm, T):
    return (np.einsum('ip,pjk->ijk', Rm, T) + np.einsum('jp,ipk->ijk', Rm, T)
            + np.einsum('kp,ijp->ijk', Rm, T)) % P
def casimir(T):
    out = np.zeros_like(T)
    for Rm in R: out = (out + deriv(Rm, deriv(Rm, T))) % P
    return out % P

kr_rows, kr_piv, kr_hist = [], [], []
minpoly = None
v = T.ravel() % P
for step in range(30):
    w = v.copy(); hist = np.zeros(step+1, dtype=np.int64); hist[step] = 1
    for r, c, h in zip(kr_rows, kr_piv, kr_hist):
        if w[c]:
            f = int(w[c]); w = (w - f*r) % P
            hist[:len(h)] = (hist[:len(h)] - f*h) % P
    nz = np.nonzero(w)[0]
    if not len(nz):
        minpoly = hist % P
        print(f"Krylov space closes at dimension {step}")
        break
    c = int(nz[0]); inv = pow(int(w[c]), P-2, P)
    kr_rows.append(w*inv % P); kr_piv.append(c); kr_hist.append(hist*inv % P)
    v = casimir(v.reshape(D,D,D)).ravel()
assert minpoly is not None

def polyeval(coef, x):
    acc = 0
    for c in reversed(coef): acc = (acc*x + int(c)) % P
    return acc

print("\nblock             c(lambda)   raw eigenvalue   root of minpoly?")
present, absent = [], []
for l, m in sorted(MULT.items()):
    c = cval(*l); raw = c*scale % P
    hit = polyeval(minpoly, raw) == 0
    (present if hit else absent).append((l, m))
    print(f"  {str(l):8s} m={m}   {c:3d}        {raw:6d}          {hit}")

def dimV(a, b): return (a-b+1)*(a+b+2)*(2*a+3)*(2*b+1)//6
print(f"\nblocks whose Casimir value is a root : {len(present)}")
print(f"  lambda_2 EVEN among them: {sum(1 for l,_ in present if l[1]%2==0)}"
      f" / {sum(1 for l in MULT if l[1]%2==0)}")
print(f"  lambda_2 ODD  among them: {sum(1 for l,_ in present if l[1]%2==1)}"
      f" / {sum(1 for l in MULT if l[1]%2==1)}")
print(f"sum of dim V_lambda over the lambda_2-even blocks = "
      f"{sum(dimV(*l) for l in MULT if l[1]%2==0)}")
print("degenerate Casimir values (blocks the spectrum alone cannot separate):")
seen = {}
for l in MULT: seen.setdefault(cval(*l), []).append(l)
for c, ls in sorted(seen.items()):
    if len(ls) > 1: print(f"   c={c}: {ls}   dims {[dimV(*l) for l in ls]}")
