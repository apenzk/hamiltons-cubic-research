"""r237, claim 3: dim (Sym^d W_n^*)^{B_n}, exactly, by Burnside over B_n.

Post 32 (audited, r232) proves k_B(Sym^6 W) >= 24 -- the module Sym^6(W_n) is
GENERATED in degree 24 over B_n, so Proposition 2.9 cannot be invoked below
n_0 = 24.  The A1 file asserts the direct route needs uniqueness "only modulo
diagram relations" and so escapes.  To confront post 32 rather than bypass it
one needs the actual B_n numbers, which nothing in the record has.

Method.  B_n = hyperoctahedral group, order 2^n n!, conjugacy classes indexed
by pairs of partitions (lam | mu) with |lam| + |mu| = n (positive and negative
cycles).  For such an element,

    p_j(g) = trace(g^j on R^n) = sum_{a in lam, a | j} a
                              + sum_{b in mu,  b | j} b * (-1)^(j/b),

    centraliser order z = prod_i (2i)^{m_i(lam)} m_i(lam)!
                        * prod_i (2i)^{m_i(mu)}  m_i(mu)!.

The space of algebraic curvature tensors is the Schur functor S_{(2,2)}, and
C_n = W_n + Sym^2(R^n) as O(n)-reps, so

    chi_W = p_1^4/12 + p_2^2/4 - p_1 p_3/3 - (p_1^2 + p_2)/2,

and chi_W(g^k) is the same expression with p_j -> p_{jk}.  Newton's identity
turns the power sums {chi_W(g^k)}_{k<=d} into h_d, and Burnside averages.
All arithmetic is exact (Fraction).
"""
import sys
from fractions import Fraction
from functools import lru_cache

def partitions(n, mx=None):
    if mx is None:
        mx = n
    if n == 0:
        yield ()
        return
    for k in range(min(n, mx), 0, -1):
        for rest in partitions(n - k, k):
            yield (k,) + rest

def zpart(lam):
    z, i = 1, 0
    from collections import Counter
    for part, m in Counter(lam).items():
        f = 1
        for t in range(1, m + 1):
            f *= t
        z *= (2 * part) ** m * f
    return z

def pj(lam, mu, j):
    t = 0
    for a in lam:
        if j % a == 0:
            t += a
    for b in mu:
        if j % b == 0:
            t += b * (-1) ** (j // b)
    return t

def chi_W(P, k):
    """character of W_n at g^k, given P[m] = p_m(g).  P must reach 4k."""
    p1, p2, p3, p4 = P[k], P[2 * k], P[3 * k], P[4 * k]
    return (Fraction(p1 ** 4, 12) + Fraction(p2 ** 2, 4) - Fraction(p1 * p3, 3)
            - Fraction(p1 ** 2 + p2, 2))

def chi_std(P, k):
    return Fraction(P[k])

def h_from_p(ps, d):
    """Newton: h_d from p_1..p_d."""
    h = [Fraction(1)] + [Fraction(0)] * d
    for m in range(1, d + 1):
        s = Fraction(0)
        for i in range(1, m + 1):
            s += ps[i] * h[m - i]
        h[m] = s / m
    return h[d]

def sym_inv_dim(n, d, chi):
    """dim (Sym^d U)^{B_n} with U's character supplied by chi(P, k)."""
    fact = 1
    for t in range(1, n + 1):
        fact *= t
    order = 2 ** n * fact
    total = Fraction(0)
    for s in range(n + 1):
        for lam in partitions(s):
            for mu in partitions(n - s):
                z = zpart(lam) * zpart(mu)
                P = {m: pj(lam, mu, m) for m in range(1, 4 * d + 1)}
                ps = {k: chi(P, k) for k in range(1, d + 1)}
                total += Fraction(order, z) * h_from_p(ps, d)
    r = total / order
    assert r.denominator == 1, (n, d, r)
    return int(r)

