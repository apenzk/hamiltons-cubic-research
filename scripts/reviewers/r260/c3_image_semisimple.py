"""CLAIM 3 -- is SEMISIMPLICITY OF B_f(n) what makes the multiplicity space irreducible?

The theorem says: B_12(12) semisimple, THEREFORE Hom_{O(n)}(V_lambda, V^{tensor 12})
is the irreducible cell module, HENCE generated by any nonzero vector.

But the multiplicity space is a module over the IMAGE nu(B_f(n)), and the double
centraliser makes that image  ⊕_lambda End(M_lambda)  for EVERY n -- a semisimple
algebra whose simple modules are exactly the M_lambda.  So irreducibility, and
with it "generated by any nonzero vector", needs no threshold at all.

This file exhibits that below Rui's threshold, where B_f(n) is NOT semisimple:

  * the trace form of the REGULAR representation of B_f(n) is degenerate
    (c2_semisimple.py: B_4(2) has rank 58 of 105, B_5(2) 745 of 945, B_5(3) 706);
  * the trace form of the SAME algebra on the module U = V^{tensor f} has rank
    equal to dim nu(B_f(n)) exactly -- i.e. the induced form on the IMAGE is
    NONDEGENERATE, so the image is semisimple.

An element of rad(A) is nilpotent and stays so after multiplication, hence has
trace 0 in EVERY representation; so a nondegenerate tr_U(xy) forces rad = 0.

tr_U is computed combinatorially, with no matrices:  D.E = n^L F  and
tr(nu(F)) = n^{#components of F closed up}.
"""
import sys, numpy as np
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from c2_semisimple import matchings, canon, compose, rank_mod, PRIMES

def closure_components(F, f):
    """tr(nu(F)) = n^{this}: close top i to bottom i and count components."""
    par = list(range(2*f))
    def find(x):
        while par[x] != x:
            par[x] = par[par[x]]; x = par[x]
        return x
    def uni(a, b):
        ra, rb = find(a), find(b)
        if ra != rb: par[ra] = rb
    for a, b in F:
        uni(a, b)
    for i in range(f):
        uni(i, i + f)
    return len({find(x) for x in range(2*f)})

for f in (3, 4, 5):
    basis = [canon(D) for D in matchings(tuple(range(2*f)))]
    N = len(basis)
    index = {D: i for i, D in enumerate(basis)}
    prod = [[compose(A, B, f) for B in basis] for A in basis]
    comp = [closure_components(F, f) for F in basis]
    print(f"\n  f = {f},  {N} diagrams")
    for n in range(2, 7):
        T = np.zeros((N, N), dtype=object)
        for i in range(N):
            for j in range(N):
                L, C = prod[i][j]
                T[i, j] = n**(L + comp[index[C]])
        rk = 0
        for p in PRIMES:
            Tp = np.array([[int(x) % p for x in r] for r in T], dtype=np.int64)
            rk = max(rk, rank_mod(Tp, p))
        print(f"    n={n}:  rank of tr_U(xy) on the {N} diagrams = {rk:>4}"
              f"    (Rui semisimple: {n >= f-1})")
        sys.stdout.flush()
