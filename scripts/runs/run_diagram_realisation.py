import numpy as np
from itertools import combinations

def matchings(pts):
    """every perfect matching of a point set, as a tuple of pairs."""
    if not pts:
        yield ()
        return
    a, rest = pts[0], pts[1:]
    for i, b in enumerate(rest):
        for m in matchings(rest[:i] + rest[i+1:]):
            yield ((a, b),) + m

def diagram_ops(m, n):
    """nu(D) on V^{tensor m}, one dense matrix per Brauer diagram.

    Points 0..m-1 are the OUTPUT legs and m..2m-1 the INPUT legs.  A matching
    edge is a Kronecker delta on the two indices it joins, so the matrix entry
    is the product of the deltas the diagram names.
    """
    dim = n ** m
    idx = [tuple((k // n**(m-1-p)) % n for p in range(m)) for k in range(dim)]
    ops = []
    for D in matchings(tuple(range(2*m))):
        M = np.zeros((dim, dim))
        for r, j in enumerate(idx):
            for c, i in enumerate(idx):
                lab = j + i
                if all(lab[a] == lab[b] for a, b in D):
                    M[r, c] = 1.0
        ops.append(M)
    return ops

def updown_counts(m):
    """dim Delta_lambda = the number of up-down tableaux of length m ending at lambda."""
    cur = {(): 1}
    for _ in range(m):
        nxt = {}
        for lam, c in cur.items():
            for k in range(len(lam) + 1):                       # add a box
                new = list(lam) + [0]
                new[k] += 1
                if all(new[t] >= new[t+1] for t in range(len(new)-1)):
                    key = tuple(x for x in new if x)
                    nxt[key] = nxt.get(key, 0) + c
            for k in range(len(lam)):                           # remove a box
                new = list(lam)
                new[k] -= 1
                if new[k] >= 0 and all(new[t] >= new[t+1] for t in range(len(new)-1)):
                    key = tuple(x for x in new if x)
                    nxt[key] = nxt.get(key, 0) + c
        cur = nxt
    return cur

def conj(lam):
    return tuple(sum(1 for p in lam if p > k) for k in range(lam[0])) if lam else ()

def admissible(lam, n):
    """O(n) labels a partition iff the first two COLUMN lengths sum to at most n."""
    c = conj(lam)
    return (c[0] if len(c) > 0 else 0) + (c[1] if len(c) > 1 else 0) <= n

def loops(D, E, f):
    """cycles in the union of two perfect matchings on 2f points."""
    m = {}
    for a, b in D:
        m.setdefault(a, []).append(b); m.setdefault(b, []).append(a)
    for a, b in E:
        m.setdefault(a, []).append(b); m.setdefault(b, []).append(a)
    seen, c = set(), 0
    for start in range(2*f):
        if start in seen:
            continue
        c += 1
        cur, prev = start, None
        while True:
            seen.add(cur)
            nxts = [x for x in m[cur] if x != prev] or [m[cur][0]]
            cur, prev = nxts[0], cur
            if cur == start:
                break
    return c

def _rank_mod(rows, ncols, q):
    """Gaussian elimination over F_q, in place, on a list of int lists."""
    r = 0
    for c in range(ncols):
        piv = next((i for i in range(r, len(rows)) if rows[i][c] % q), None)
        if piv is None:
            continue
        rows[r], rows[piv] = rows[piv], rows[r]
        inv = pow(rows[r][c], q - 2, q)
        rows[r] = [(v * inv) % q for v in rows[r]]
        for i in range(len(rows)):
            if i != r and rows[i][c] % q:
                fac = rows[i][c]
                rows[i] = [(a - fac * b) % q for a, b in zip(rows[i], rows[r])]
        r += 1
        if r == len(rows):
            break
    return r

def image_dim(f, n):
    """dim nu(B_f(n)) as the rank of the diagram Gram matrix [ n^{loops(D,E)} ].

    WHY THE RANK IS dim nu, asked by four reviewers and unrecorded until now: the
    Gram is [ <nu(D), nu(E)> ] under the FROBENIUS form <A,B> = tr(A^T B), whose
    value on two diagrams is n^{loops(D,E)}.  The Frobenius form is POSITIVE
    DEFINITE on real matrices, so the Gram matrix of a spanning set has rank equal
    to the dimension of its span.  Without definiteness a Gram rank only bounds
    that dimension.

    The matrix is (2f-1)!! square and its SIZE DOES NOT DEPEND ON n, which is what
    makes f = 5 reachable -- the dense n^f x n^f route this file first used is
    7776 x 7776 at (5,6) for every one of 945 diagrams, and sympy's exact rank on
    the 945 x 945 Gram is itself too slow.  Rank is taken modulo TWO 31-bit primes:
    the rank is taken modulo two 31-bit primes, and cross-checked exactly.

    THE JUSTIFICATION THIS FILE FIRST GAVE WAS A NON SEQUITUR (r262).  It argued
    that "a modular rank can only understate the rational one, so agreement
    between two primes licenses reading it as exact".  It does not: rank_p <=
    rank_Q for EVERY p, so k agreeing primes bound the rank from BELOW only, and
    k primes sharing a bad pivot agree with each other while all understating.
    r261 exhibits the failure directly -- p = 11 returns 602 at (f,n) = (5,3)
    where the rank is 603.

    THE REPAIR THAT REPLACED IT WAS CIRCULAR (r263).  Saying "the upper bound
    comes from the identity dim nu = sum m_lambda(n)^2, asserted per cell below"
    names the CONCLUSION as the premise -- that identity is what the table exists
    to test.

    WHAT IS ACTUALLY FREE IS THE CONTAINMENT.  Every nu(D) is an O(n)-equivariant
    endomorphism, by inspection and with no FFT needed, so

        nu(B_f(n))  is contained in  End_{O(n)}(V^{tensor f}),

    and taking dimensions gives the INEQUALITY dim nu <= sum m_lambda(n)^2.  That
    is what turns a modular LOWER bound attaining the prediction into a proof:
    lower bound from the primes, upper bound from the containment, and they meet.
    The exact rational rank is computed below wherever it is affordable as a
    further check.
    """
    Ds = list(matchings(tuple(range(2*f))))
    N = len(Ds)
    G = [[n ** loops(Ds[i], Ds[j], f) for j in range(N)] for i in range(N)]
    primes = (2147483647, 2147483629)
    ranks = {_rank_mod([row[:] for row in G], N, q) for q in primes}
    assert len(ranks) == 1, (
        f"the {len(primes)} primes disagree on rank at (f,n) = ({f},{n}): {ranks}; each is a "
        "lower bound for the rational rank, so disagreement means at least one prime "
        "divides a pivot -- take the maximum only after checking why")
    return max(ranks), N

def restricted_updown(f, n):
    """m_lambda(n): up-down tableaux of length f whose EVERY step is O(n)-admissible.

    The unrestricted count is dim Delta_lambda, the ABSTRACT cell module.  Filtering
    the intermediate shapes as well is what makes the count the true multiplicity at
    finite n, and it is the difference the reviewers identified: the two agree
    exactly when n >= f-1 and part company below.
    """
    cur = {(): 1}
    for _ in range(f):
        nxt = {}
        for lam, c in cur.items():
            for k in range(len(lam) + 1):
                new = list(lam) + [0]; new[k] += 1
                if all(new[t] >= new[t+1] for t in range(len(new)-1)):
                    key = tuple(x for x in new if x)
                    if admissible(key, n):
                        nxt[key] = nxt.get(key, 0) + c
            for k in range(len(lam)):
                new = list(lam); new[k] -= 1
                if new[k] >= 0 and all(new[t] >= new[t+1] for t in range(len(new)-1)):
                    key = tuple(x for x in new if x)
                    if admissible(key, n):
                        nxt[key] = nxt.get(key, 0) + c
        cur = nxt
    return cur

def image_dim_exact(f, n):
    """dim nu(B_f(n)) over Q, by fraction-free elimination on the same Gram."""
    from fractions import Fraction as F
    Ds = list(matchings(tuple(range(2*f))))
    N = len(Ds)
    M = [[F(n ** loops(Ds[i], Ds[j], f)) for j in range(N)] for i in range(N)]
    r = 0
    for c in range(N):
        piv = next((i for i in range(r, N) if M[i][c] != 0), None)
        if piv is None:
            continue
        M[r], M[piv] = M[piv], M[r]
        for i in range(r + 1, N):
            if M[i][c] != 0:
                fac = M[i][c] / M[r][c]
                M[i] = [a - fac * b for a, b in zip(M[i], M[r])]
        r += 1
    return r

