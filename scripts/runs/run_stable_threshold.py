"""Where the O(n) invariant count of Weyl_n reaches its stable value.

plan.md carries n >= 4k, derived by row-counting.  Reviewer 179 reports the
sharp threshold is n >= 2k.  This checks that independently at k = 4, where the
stable value is 7: the claim predicts 7 at n = 8 = 2k and strictly less at n = 7.

Same Weyl integration as run_n5_constraint_count.py, generalised to B_r and D_r:
  dim V^G = (1/|W|) CT[ chi_V(t) * prod_{alpha in Phi} (1 - t^alpha) ],
Sym^k characters from the power sums by Newton.  Exponents are doubled so that
B_r's half-integral rho stays integral.
"""
from fractions import Fraction as F
from itertools import product

def mul(P, Q):
    R = {}
    for k1, c1 in P.items():
        for k2, c2 in Q.items():
            k = tuple(a+b for a, b in zip(k1, k2)); R[k] = R.get(k, 0) + c1*c2
    return {k: c for k, c in R.items() if c}
def add(P, Q):
    R = dict(P)
    for k, c in Q.items(): R[k] = R.get(k, 0) + c
    return {k: c for k, c in R.items() if c}
def scal(a, P): return {k: a*c for k, c in P.items() if a*c}
def subst(P, j): return {tuple(j*x for x in k): c for k, c in P.items()}

def setup(r, D):
    """Weyl group (as signed permutations), 2*rho, and the roots, for B_r or D_r."""
    from itertools import permutations
    W = []
    for perm in permutations(range(r)):
        for signs in product((1, -1), repeat=r):
            if D and (signs.count(-1) % 2): continue        # D_r: even sign changes
            det = 1
            p = list(perm); seen = [False]*r; cyc = 0
            for i in range(r):
                if not seen[i]:
                    cyc += 1; j = i
                    while not seen[j]: seen[j] = True; j = p[j]
            det = (-1) ** (r - cyc)
            for s in signs: det *= s
            if D: det = (-1) ** (r - cyc)                    # sign changes are even
            W.append((perm, signs, det))
    rho2 = tuple(2*(r-1-i) for i in range(r)) if D else tuple(2*(r-i)-1 for i in range(r))
    roots = []
    for i in range(r):
        for j in range(i+1, r):
            for si in (1, -1):
                for sj in (1, -1):
                    v = [0]*r; v[i] = si; v[j] = sj; roots.append(tuple(v))
        if not D:
            for si in (1, -1):
                v = [0]*r; v[i] = si; roots.append(tuple(v))
    return W, rho2, roots

def act(w, v):
    perm, signs, _ = w
    return tuple(signs[i]*v[perm[i]] for i in range(len(v)))

def alternant(mu2, W):
    P = {}
    for w in W:
        k = act(w, mu2); P[k] = P.get(k, 0) + w[2]
    return {k: c for k, c in P.items() if c}

def divide(Nn, Dd):
    Nn = dict(Nn); Q = {}
    dl = max(Dd); dc = Dd[dl]
    while Nn:
        nl = max(Nn); k = tuple(a-b for a, b in zip(nl, dl)); c = F(Nn[nl], dc)
        Q[k] = Q.get(k, 0) + c
        for dk, dv in Dd.items():
            kk = tuple(a+b for a, b in zip(dk, k)); Nn[kk] = Nn.get(kk, 0) - c*dv
        Nn = {a: b for a, b in Nn.items() if b}
    return {k: (int(c) if c.denominator == 1 else c) for k, c in Q.items()}

def weyl_module(r, D):
    """the character of [2,2] = Weyl_n, n = 2r+1 (B) or 2r (D)."""
    W, rho2, roots = setup(r, D)
    lam = [2, 2] + [0]*(r-2)
    lam2 = tuple(2*lam[i] + rho2[i] for i in range(r))
    return divide(alternant(lam2, W), alternant(rho2, W)), W, roots

def invariant_dims(r, D, K):
    chi, W, roots = weyl_module(r, D)
    n = 2*r + (0 if D else 1)
    dim = sum(chi.values())
    p = {j: subst(chi, j) for j in range(1, K+1)}
    h = {0: {tuple([0]*r): F(1)}}
    out = []
    for k in range(1, K+1):
        acc = {}
        for j in range(1, k+1): acc = add(acc, mul(p[j], h[k-j]))
        h[k] = scal(F(1, k), acc)
        Q = dict(h[k])
        for a in roots:
            Q = add(Q, scal(-1, {tuple(kk+2*aa for kk, aa in zip(kk_, a)): c
                                 for kk_, c in Q.items()}))
        out.append(Q.get(tuple([0]*r), 0) / len(W))
    return n, dim, out

print("k = 4: the stable value is 7; n >= 2k predicts 7 at n = 8, less at n = 7")
for r, D in ((3, False), (4, True)):
    n, dim, v = invariant_dims(r, D, 4)
    tag = "= O(n), since -I acts trivially and O = SO x {+-I} at odd n" if not D \
          else "SO(n) ONLY -- see below"
    print(f"  n = {n:2d}  dim Weyl_n = {dim:4d}   {[int(x) for x in v]}   {tag}")

