"""The B_n route to transfer: what it needs, and the half that is now proved.

THE SETTING.  Levin-Chandrasekaran's Theorem 3.5 does not apply to {O_n} at all --
the presentation degree is undefined there, O(d) x O(n-d) having infinite index
(reviewer 227).  Their own fallback, which they use themselves, is to run the
machinery over the finite group sequence {B_n} of SIGNED PERMUTATIONS, where every
degree is computable.  That yields a unique B_n-invariant extension of a
description given at n_0.

  THE QUESTION THAT DECIDES THE ROUTE: is that extension O(n)-invariant?

WHAT THIS LEMMA DOES AND DOES NOT BUY.  It is enough that the extension be
invariant under B_n and under the embedded block O(n_0), because those two
together GENERATE O(n).  BUT THE REDUCTION IS AN EQUIVALENCE, NOT A HALVING
(reviewer 231): given B_n-invariance, which holds by construction,
block-O(n_0)-invariance and O(n)-invariance are logically equivalent, and an
equivalence answers no part of a question.  231 also shows the block is not
minimal -- a single generator L_01 cuts exactly as far, so the residual is one
1-parameter subgroup whatever n_0 is -- and that "a statement at one dimension"
was wrong, the block acting on all n coordinates and being itself continuous.

  THE LEMMA IS SUPERSEDED by run_bn_transfer_theorem.py, which proves
  O(n)-invariance outright via the first fundamental theorem, with block
  invariance a corollary.  It is kept because its statement is true and its
  proof is short.

The generation statement itself:

  Lemma.  For n_0 >= 2 and n >= n_0, the group generated by B_n and the block
  O(n_0) acting on the first n_0 coordinates is all of O(n).

  Proof.  B_n contains every coordinate permutation, so conjugating the block
  moves it onto any n_0-subset of coordinates.  Since n_0 >= 2, each such block
  contains the rotations of every coordinate 2-plane inside it, and as the subset
  ranges over all n_0-subsets those 2-planes range over ALL coordinate 2-planes.
  Givens' theorem: rotations in coordinate 2-planes generate SO(n).  B_n supplies
  a single sign flip, of determinant -1, so the group is O(n).  QED

So the route reduces from "is the extension O(n)-invariant", a statement about a
continuous group, to "is the extension invariant under the single block O(n_0)",
a statement at one dimension.

WHAT IS STILL OWED, AND IT IS THE HARD HALF.  The extension restricts at level
n_0 to u_{n_0}, which IS O(n_0)-invariant -- but that is invariance of the
RESTRICTION, and what is needed is invariance of the extension under the block
acting on all n coordinates, the block fixing the other n - n_0 pointwise.  Those
are different statements and nothing here bridges them.

This file proves the lemma and screens it; it does not close the route.
"""
import numpy as np

rng = np.random.default_rng(0)

def givens(n, i, j, t):
    G = np.eye(n); c, s = np.cos(t), np.sin(t)
    G[i, i] = c; G[j, j] = c; G[i, j] = -s; G[j, i] = s
    return G

def signed_perm(n, rs):
    P = np.zeros((n, n))
    for i, j in enumerate(rs.permutation(n)):
        P[i, j] = rs.choice([-1.0, 1.0])
    return P

# SCREEN, NOT PROOF.  The lemma is proved in the docstring; this checks the
# construction it rests on -- that conjugating a block by coordinate permutations
# reaches every coordinate 2-plane -- by counting the planes actually reached.
for n, n0 in ((6, 2), (8, 3), (12, 2), (12, 4)):
    reached = set()
    for _ in range(4000):
        P = signed_perm(n, rng)
        # the block acts on coordinates 0..n0-1; conjugation by P moves it to
        # the image of that set under P's underlying permutation
        img = sorted(int(np.flatnonzero(P[:, k])[0]) for k in range(n0))
        for a in range(len(img)):
            for b in range(a + 1, len(img)):
                reached.add((img[a], img[b]))
    total = n * (n - 1) // 2
    print(f"  n={n:>3} n_0={n0}:  coordinate 2-planes reached "
          f"{len(reached):>3} of {total:>3}")
    assert len(reached) == total, (
        f"only {len(reached)} of {total} coordinate 2-planes are reachable by "
        f"conjugating the O({n0}) block by signed permutations.  The lemma's "
        "proof claims all of them, and Givens' theorem needs all of them to "
        "generate SO(n)")

# and the determinant claim: B_n supplies an element of determinant -1
d = np.linalg.det(np.diag([-1.0] + [1.0] * 11))
assert abs(d + 1) < 1e-12, "B_n must contain a determinant -1 element or the group generated is only SO(n)"
print(f"\n  a single sign flip has determinant {d:.0f}, so the group is O(n) and not SO(n)")
print("\n  LEMMA PROVED (docstring).  The route now turns on the OTHER half:")
print("  invariance of the extension under the block O(n_0) acting on all n")
print("  coordinates -- which does NOT follow from O(n_0)-invariance of its")
print("  restriction, and is not established here.")
