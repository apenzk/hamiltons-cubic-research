"""Generate each block's copy of V_lambda inside Sym^3(Weyl_5) by lowering.

This is the dictionary the SDP needs.  The 36 Gram unknowns are entries
(G_lam)_{ij} on multiplicity spaces; turning each into a coefficient against the
14 invariant sextics needs the pairing <v_i, v_j> of the V_lambda-components of
W^3 in copies i and j -- and those components require the copies themselves,
not just their highest-weight vectors.

A copy is generated from its highest-weight vector by the two lowering
operators.  Validated per block against the Weyl dimension formula before
anything downstream uses it.
"""
from fractions import Fraction as F
from itertools import combinations_with_replacement
import importlib.util, sys, os, time

d = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("hw", os.path.join(d, "run_n5_highest_weight.py"))
hw = importlib.util.module_from_spec(spec)
_o = sys.stdout; sys.stdout = open(os.devnull, "w")
spec.loader.exec_module(hw); sys.stdout = _o

G, ZERO, ONE, I = hw.G, hw.ZERO, hw.ONE, hw.I
MONO, MIDX, WWT, HW = hw.MONO, hw.MIDX, hw.WWT, hw.HW
print(f"loaded: {len(MONO)} monomials, {sum(len(v[1]) for v in HW.values())} hw vectors",
      flush=True)

# --- the two lowering operators, as weight-basis matrices on Weyl_5 ---
RV1m, RV2m = hw.root_vector(-1, 1), hw.root_vector(0, -1)
F1 = hw.lin({k: RV1m[k] for k in range(10) if RV1m[k]})
F2 = hw.lin({k: RV2m[k] for k in range(10) if RV2m[k]})
F1C = hw.to_weight_coords([hw.apply(F1, v) for v in hw.WBASIS])
F2C = hw.to_weight_coords([hw.apply(F2, v) for v in hw.WBASIS])
for nm, EC, a in (("F1", F1C, (-1, 1)), ("F2", F2C, (0, -1))):
    ok = all(not EC[j][k] or (WWT[k][0] == WWT[j][0]+a[0] and WWT[k][1] == WWT[j][1]+a[1])
             for j in range(35) for k in range(35))
    print(f"  {nm} shifts every weight by {a}: {ok}", flush=True)

def lower(vec, EC):
    """apply a lowering operator to a Sym^3 element {monomial index: coeff}."""
    out = {}
    for idx, co in vec.items():
        a, b, c = MONO[idx]
        for pos, x in enumerate((a, b, c)):
            rest = [y for j, y in enumerate((a, b, c)) if j != pos]
            for t in range(35):
                if EC[x][t]:
                    j = MIDX[tuple(sorted(rest + [t]))]
                    out[j] = out.get(j, ZERO) + co*EC[x][t]
    return {k: v for k, v in out.items() if v}

def dimB2(l): return (l[0]-l[1]+1)*(l[0]+l[1]+2)*(2*l[0]+3)*(2*l[1]+1)//6

def generate(u, cap):
    """span of the module generated by u under lowering, as an echelon dict."""
    ech = {}                       # pivot monomial -> reduced vector
    frontier = [u]
    total = 0
    while frontier and total < cap:
        nxt = []
        for v in frontier:
            # Reduce on the LEADING term, repeatedly.  Iterating a snapshot of
            # the original keys misses pivots introduced by the reduction
            # itself, leaving dependent vectors nonzero and over-counting the
            # block -- which is exactly how (4,0) read 56 against 55.
            w = dict(v)
            while w:
                piv = max(w)
                if piv not in ech: break
                f = w[piv] / ech[piv][piv]
                for k, c in ech[piv].items():
                    w[k] = w.get(k, ZERO) - f*c
                w = {k: c for k, c in w.items() if c}
            if not w: continue
            piv = max(w)
            ech[piv] = w; total += 1
            nxt.append(lower(w, F1C)); nxt.append(lower(w, F2C))
        frontier = [x for x in nxt if x]
    return total

print("\n=== generating copies, smallest blocks first ===", flush=True)
t0 = time.time()
for lam in sorted(HW, key=lambda l: dimB2(l)):
    cols, ns = HW[lam]
    want = dimB2(lam)
    if want > 900:
        print(f"  ... stopping before {lam} at dim {want}", flush=True); break
    # Every copy, not only ns[0]: 17 of the 41 were never built, so 24 of the
    # 41 multiplicities had gone unchecked (reviewer 182).  The cap is generous
    # so an over-count is reported rather than clipped -- a censored number
    # reads as a measurement and the (3,1) figure of 86 was exactly that.
    for i, v in enumerate(ns):
        u = {cols[j]: v[j] for j in range(len(cols)) if v[j]}
        got = generate(u, 3*want)
        print(f"  lambda={lam} copy {i+1}/{len(ns)}  generated {got:4d}  "
              f"want {want:4d}  {'OK' if got == want else '!!'}   "
              f"[{time.time()-t0:.0f}s]", flush=True)
